begin;
create extension if not exists pgtap with schema extensions;
set local search_path = public, extensions;
select plan(9);
select ok((select relrowsecurity from pg_class where oid='public.teachers'::regclass),'Teacher RLS remains enabled');
select ok(not has_function_privilege('anon','public.update_teacher_profile(uuid,text,text,text,text,text,numeric)','EXECUTE'),'Anonymous cannot edit profiles');
create temporary table test_teacher as select t.id, p.full_name, p.phone from public.teachers t join public.profiles p on p.id=t.user_id limit 1;
grant select on test_teacher to authenticated;
select set_config('request.jwt.claims',json_build_object('sub',(select id from public.profiles where role='super_admin' and is_active limit 1),'role','authenticated')::text,true);
set local role authenticated;
select lives_ok($$select public.update_teacher_profile(id,full_name,phone,'TEST','TEST','part_time',150000) from test_teacher$$,'Manager saves hourly rate and employment');
select is((select hourly_rate from public.teachers where id=(select id from test_teacher)),150000::numeric,'Hourly rate persisted');
select throws_ok($$select public.update_teacher_profile(id,full_name,phone,'TEST','TEST','invalid',100) from test_teacher$$,'23514',null,'Invalid employment rejected');
select throws_ok($$select public.update_teacher_profile(id,full_name,phone,'TEST','TEST','full_time',-1) from test_teacher$$,'23514',null,'Negative rate rejected');
select throws_ok($$select public.update_teacher_profile(id,full_name,phone,'TEST','TEST','full_time',1.5) from test_teacher$$,'23514',null,'Fractional VND rejected');
select lives_ok($$select public.update_teacher_profile(id,full_name,phone,'TEST','TEST','full_time',0) from test_teacher$$,'Zero rate is valid');
select lives_ok($$select public.update_teacher_profile(id,full_name,phone,'TEST','TEST',null,null) from test_teacher$$,'Unset employment and rate allowed');
reset role;
select * from finish();
rollback;
